    // Llena el combo; la primera opcion es "Todos los municipios" (id 0)
    @SuppressWarnings({"unchecked", "rawtypes"})
    public void cargarMunicipios(java.util.List<modelo.Municipio> lista) {
        java.util.List<modelo.Municipio> opciones = new java.util.ArrayList<modelo.Municipio>();
        opciones.add(new modelo.Municipio(0, "Todos los municipios", 0));
        opciones.addAll(lista);
        cmbMunicipio.setModel(new javax.swing.DefaultComboBoxModel(opciones.toArray()));
    }

    public modelo.Municipio getMunicipioSeleccionado() {
        return (modelo.Municipio) cmbMunicipio.getSelectedItem();
    }

    // Actualiza la grafica y los contadores
    public void mostrarDatos(int pendientes, int resueltos) {
        lblPendientes.setText("Pendientes: " + pendientes);
        lblResueltos.setText("Resueltas: " + resueltos);
        lblTotal.setText("Total: " + (pendientes + resueltos));
        grafica.setDatos(pendientes, resueltos);
    }

